package io.github.wwalkerrocks.puzzlebot

import io.github.wwalkerrocks.puzzlebot.core.BoardReader
import org.junit.Test
import java.io.File

/**
 * Rebuilds DigitTemplateData.kt from the labelled screenshots. Run with -DregenTemplates=true;
 * otherwise it only prints what it would write.
 */
class TemplateGenerator {
    @Test
    fun generate() {
        val n = BoardReader.GW * BoardReader.GH
        val sum = Array(10) { DoubleArray(n) }
        val asp = DoubleArray(10)
        val cnt = IntArray(10)
        for ((name, board) in Screens.boards) for (width in listOf(923, 1080)) {
            val img = Screens.load(name, width)
            val (grid, why) = BoardReader.detectGrid(img)
            checkNotNull(grid) { "$name@$width: $why" }
            for (cell in board.indices) {
                val v = board[cell]
                val glyphs = BoardReader.readCell(img, grid, cell)!!
                if (v == 0) { check(glyphs.isEmpty()); continue }
                val digits = if (v >= 10) listOf(v / 10, v % 10) else listOf(v)
                check(glyphs.size == digits.size) { "$name cell $cell: ${glyphs.size} glyphs for $v" }
                for ((g, d) in glyphs.zip(digits)) {
                    for (i in 0 until n) sum[d][i] += g.cells[i].toDouble()
                    asp[d] += g.aspect.toDouble()
                    cnt[d]++
                }
            }
        }
        val src = buildString {
            appendLine("package io.github.wwalkerrocks.puzzlebot.core")
            appendLine()
            appendLine("// Generated by TemplateGenerator from the labelled screenshots in src/test/resources/screens.")
            appendLine("// Samples per digit: ${cnt.joinToString()}")
            appendLine("internal object DigitTemplateData {")
            appendLine("    val CELLS = arrayOf(")
            for (d in 0..9) {
                val row = (0 until n).joinToString(", ") { "%.3ff".format(sum[d][it] / cnt[d]) }
                appendLine("        floatArrayOf($row),")
            }
            appendLine("    )")
            appendLine("    val ASPECT = floatArrayOf(${(0..9).joinToString(", ") { "%.3ff".format(asp[it] / cnt[it]) }})")
            appendLine("}")
        }
        println("samples per digit: ${cnt.joinToString()}")
        if (System.getProperty("regenTemplates") == "true") {
            File(System.getProperty("templateOut")!!).writeText(src)
            println("wrote templates")
        }
    }
}
